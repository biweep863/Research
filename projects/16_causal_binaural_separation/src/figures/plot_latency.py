def gap_terms(orc, ev, head, L, steps=None):
    """Decompose the causal stft_asym loss at latency L w.r.t. 32 ms (all in dB SI-SDRi)."""
    c32 = run_get(ev, "stft_asym", 32, head, steps=steps)
    cL = run_get(ev, "stft_asym", L, head, steps=steps)
    ncL = run_get(ev, "stft_asym", L, head, causal=False, steps=steps)
    o = dict((lat, v) for lat, v in oracle_curve(orc, "oracle_ear", "asym")) if orc else {}
    if None in (c32, cL) or 32.0 not in o or float(L) not in o:
        return None
    t = {"total": c32[0] - cL[0], "resolution": o[32.0][0] - o[float(L)][0]}
    if ncL is not None:
        t["future"] = ncL[0] - cL[0]
        t["learning"] = o[float(L)][0] - ncL[0]
    return t


def fig_gap(orc, ev, head, lats, out: Path, long_steps=None, short_steps=2000):
    fig, ax = col_fig(0.7)
    keys = [("total", "Total (causal 32 ms $-$ causal L)", "#555555"),
            ("resolution", "Window (oracle 32 ms $-$ oracle L)", "#1f5fbf"),
            ("future", "Future (non-causal $-$ causal)", "#d9822b"),
            ("learning", "Learning (oracle $-$ non-causal)", "#9b59b6")]
    groups = [(L, None, f"{L:g} ms, {short_steps // 1000}k steps") for L in lats]
    if long_steps:
        groups += [(L, long_steps, f"{L:g} ms, {long_steps // 1000}k steps") for L in lats]
    w = 0.2
    labels = []
    for i, (L, st, lab_fmt) in enumerate(groups):
        t = gap_terms(orc, ev, head, L, steps=st) or {}
        labels.append(lab_fmt)
        for k, (key, lab, col) in enumerate(keys):
            if key in t:
                bars = ax.bar(i + (k - 1.5) * w, t[key], w, color=col, label=lab if i == 0 else None)
                ax.bar_label(bars, fmt="%.2f", fontsize=5, padding=1)
    ax.axhline(0, color="k", lw=0.6)
    ax.set_xticks(range(len(groups)))
    ax.set_xticklabels(labels)
    ax.set_ylabel("dB SI-SDRi")
    ax.legend(fontsize=5.5, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=2)
    ax.margins(y=0.12)
    fig.savefig(out / "gap_decomposition.pdf")
    plt.close(fig)


def _per_utt(R: Path, name: str, metric="si_sdr_i"):
    f = R / "eval" / f"{name}.json"
    return np.asarray(json.loads(f.read_text())["test"]["per_utt"][metric]) if f.exists() else None


def _paired_ci(d: np.ndarray, n_boot: int = 1000, seed: int = 0):
    rng = np.random.default_rng(seed)
    bs = np.array([rng.choice(d, len(d)).mean() for _ in range(n_boot)])
    return float(d.mean()), float(np.quantile(bs, 0.025)), float(np.quantile(bs, 0.975))


def fig_lookahead(ev, R: Path, cfg_budget, head, fs, out: Path):
    """Left: one latency budget split between window and lookahead.
    Right: hop-matched pairs -- the same hop with vs without D lookahead frames,
    which removes the frames-per-step training confound (doc/05)."""
    from src.models.factory import run_name

    split, pairs = [], []
    for name, r in ev["runs"].items():
        s = r["spec"]
        if s["family"] != "stft_asym" or not s.get("causal", True) or s.get("head") != head or s.get("steps"):
            continue
        D = s.get("lookahead", 0)
        if float(s["latency_ms"]) == float(cfg_budget):
            split.append((D, cfg_budget / (2 + D), r["test"]["si_sdr_i"]))
        if D:
            hop_ms = s["latency_ms"] / (2 + D)
            base = run_name({"family": "stft_asym", "latency_ms": 2 * hop_ms, "head": head, "causal": True})
            x, y = _per_utt(R, base), _per_utt(R, name)
            if x is not None and y is not None:
                pairs.append((D, hop_ms, _paired_ci(y - x)))
    if not split:
        return [], []
    split.sort()
    pairs.sort()
    apply_style()
    fig, axes = plt.subplots(1, 2, figsize=(3.4, 2.0), gridspec_kw={"width_ratios": [1.2, 1]})
    ax = axes[0]
    xs = np.arange(len(split))
    m = np.array([p[2][0] for p in split])
    ax.errorbar(xs, m, yerr=[m - np.array([p[2][1] for p in split]), np.array([p[2][2] for p in split]) - m],
                color="#1f5fbf", marker="o", capsize=2)
    ax.set_xticks(xs)
    ax.set_xticklabels([f"D={p[0]}\nhop {p[1]:g}" for p in split], fontsize=5.5)
    ax.set_ylabel("SI-SDRi (dB)")
    ax.set_title(f"{cfg_budget:g} ms budget", fontsize=7)
    ax = axes[1]
    if pairs:
        xs = np.arange(len(pairs))
        m = np.array([p[2][0] for p in pairs])
        ax.errorbar(xs, m, yerr=[m - np.array([p[2][1] for p in pairs]), np.array([p[2][2] for p in pairs]) - m],
                    color="#d9822b", marker="s", ls="none", capsize=2)
        ax.axhline(0, color="k", lw=0.6)
        ax.set_xticks(xs)
        ax.set_xticklabels([f"+{p[0] * p[1]:g} ms\n(hop {p[1]:g})" for p in pairs], fontsize=5.5)
        ax.set_ylabel(r"$\Delta$ SI-SDRi from lookahead (dB)", fontsize=6)
        ax.set_title("same hop, ±lookahead", fontsize=7)
    fig.tight_layout()
    fig.savefig(out / "lookahead_split.pdf")
    plt.close(fig)
    return split, pairs


def fig_rtf(bench, out: Path):
    rows = bench["rows"]
    fig, ax = col_fig(0.65)
    fams = [f for f in FAM_STYLE if any(r["family"] == f for r in rows)]
    lats = sorted({r["latency_ms"] for r in rows})
    w = 0.8 / max(len(fams), 1)
    for k, fam in enumerate(fams):
        xs, ys, ps = [], [], []
        for i, L in enumerate(lats):
            r = next((r for r in rows if r["family"] == fam and r["latency_ms"] == L), None)
            if r:
                xs.append(i + (k - (len(fams) - 1) / 2) * w)
                ys.append(r["rtf_median"])
                ps.append(r["rtf_p99"])
        st = FAM_STYLE[fam]
        ax.bar(xs, ys, w, color=st["color"], label=st["label"].split(" (")[0])
        ax.scatter(xs, ps, color="k", marker="_", s=30, zorder=3)
    ax.axhline(1.0, color="#c0392b", ls=":", lw=1)
    ax.set_yscale("log")
    ax.set_xticks(range(len(lats)))
    ax.set_xticklabels([f"{L:g}" for L in lats])
    ax.set_xlabel("Algorithmic latency (ms)")
    ax.set_ylabel("Real-time factor (CPU, 1 thread)")
    ax.legend(fontsize=6, frameon=False)
    fig.savefig(out / "rtf.pdf")
    plt.close(fig)


def table_main(ev, orc, head, out_tex: Path, lats):
    """LaTeX table: per (model, latency) SI-SDRi, ESTOI, target cue errors, held-out SI-SDRi."""
    lines = [r"\begin{tabular}{llrrrrr}", r"\toprule",
             r"Model & $L$ & SI-SDRi & ESTOI & $|\Delta$ITD$|$ & $|\Delta$ILD$|$ & held-out \\",
             r" & (ms) & (dB) & & ($\mu$s) & (dB) & SI-SDRi \\", r"\midrule"]

    def row(label, L, t, h):
        lines.append(f"{label} & {L:g} & {t['si_sdr_i'][0]:.2f} & {t['estoi'][0]:.3f} & {t['d_itd_us'][0]:.1f} & "
                     f"{t['d_ild_db'][0]:.2f} & " + (f"{h['si_sdr_i'][0]:.2f}" if h else "--") + r" \\")

    if orc:
        un = {e["set"]: e["summary"] for e in orc["entries"] if e["kind"] == "unprocessed"}
        if "test" in un:
            lines.append(f"Unprocessed & -- & 0.00 & {un['test']['estoi'][0]:.3f} & {un['test']['d_itd_us'][0]:.1f} & "
                         f"{un['test']['d_ild_db'][0]:.2f} & 0.00 \\\\")
    for fam in FAM_STYLE:
        for L in lats:
            for causal in (True, False):
                for r in ev["runs"].values():
                    s = r["spec"]
                    if s["family"] == fam and float(s["latency_ms"]) == float(L) and s.get("causal", True) == causal \
                            and not s.get("lookahead", 0):
                        lab = FAM_STYLE[fam]["label"].split(" (")[0]
                        lab += "" if causal else " (non-causal)"
                        lab += f" ({s['steps'] // 1000}k steps)" if s.get("steps") else ""
                        lab += "" if s.get("head") == head else f" ({s.get('head')} head)"
                        row(lab, L, r["test"], r.get("heldout"))
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_tex.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="paper/figures")
    ap.add_argument("--macros", default="paper/macros.tex")
    ap.add_argument("--config", default="configs/local_small.yaml")
    args = ap.parse_args()
    import yaml

    cfg = yaml.safe_load(open(args.config))
    apply_style()
    R = Path(args.results)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    orc, ev, bench, data = load(R)
    head = cfg["sweep"]["head"]
    M = Macros()
    synthetic = bool((ev or {}).get("synthetic_data")) or bool((orc or {}).get("synthetic_data"))
    M.text("DataKind", "synthetic fallback data" if synthetic else "real speech and noise")

    if data:
        M.num("NumTest", data["sets"]["test"]["n"], "{:d}")
        M.num("NumHeldout", data["sets"]["heldout"]["n"], "{:d}")
        M.num("TestSeconds", data["sets"]["test"]["seconds"], "{:g}")
        M.num("SpeechTrainHours", data["speech"]["train"]["hours"], "{:.1f}")
        M.num("RoomsTrain", data["banks"]["train"]["rooms"], "{:d}")

    if orc:
        fig_quality(orc, ev, head, out) if ev else fig_quality(orc, None, head, out)
        un = {e["set"]: e["summary"] for e in orc["entries"] if e["kind"] == "unprocessed"}
        M.num("UnprocEstoi", un["test"]["estoi"][0], "{:.3f}")
        M.num("UnprocItd", un["test"]["d_itd_us"][0], "{:.1f}")
        M.num("UnprocIld", un["test"]["d_ild_db"][0])
        for e in orc["entries"]:
            if e["kind"] == "floor":
                M.num(f"FloorItd{e['window']}", e["summary"]["d_itd_us"][0], "{:.1f}")
                M.num(f"FloorIld{e['window']}", e["summary"]["d_ild_db"][0])
        for kind, tag in (("oracle_ear", "OracleEar"), ("oracle_common", "OracleCommon"), ("wiener", "Wiener")):
            for win in ("asym", "sym"):
                for L, v in oracle_curve(orc, kind, win):
                    M.num(f"{tag}{win.capitalize()}{L:g}ms", v[0])
                for L, v in oracle_curve(orc, kind, win, metric="estoi"):
                    M.num(f"{tag}{win.capitalize()}Estoi{L:g}ms", v[0], "{:.3f}")
                for L, v in oracle_curve(orc, kind, win, metric="d_itd_us"):
                    M.num(f"{tag}{win.capitalize()}Itd{L:g}ms", v[0], "{:.1f}")
                for L, v in oracle_curve(orc, kind, win, metric="d_ild_db"):
                    M.num(f"{tag}{win.capitalize()}Ild{L:g}ms", v[0])
        o = dict(oracle_curve(orc, "oracle_ear", "asym"))
        s = dict(oracle_curve(orc, "oracle_ear", "sym"))
        if 1.0 in o and 1.0 in s:
            M.num("OracleAsymGainOnems", o[1.0][0] - s[1.0][0])
        if 4.0 in o and 4.0 in s:
            M.num("OracleAsymGainFourms", o[4.0][0] - s[4.0][0])

    gap = None
    if ev:
        fig_quality(orc, ev, head, out)
        fig_cues(orc, ev, head, out)
        lats = sorted({float(r["spec"]["latency_ms"]) for r in ev["runs"].values()})
        for r in ev["runs"].values():
            s = r["spec"]
            tag = f"{s['family'].replace('_', '')}{s['latency_ms']:g}ms{s.get('head', '')}"
            tag += "" if s.get("causal", True) else "nc"
            tag += f"la{s['lookahead']}" if s.get("lookahead", 0) else ""
            tag += "long" if s.get("steps") else ""
            for metric, key, fmt in (("si_sdr_i", "", "{:.2f}"), ("estoi", "Estoi", "{:.3f}"),
                                     ("d_itd_us", "Itd", "{:.1f}"), ("d_ild_db", "Ild", "{:.2f}"),
                                     ("d_ipd_rad", "Ipd", "{:.2f}"), ("res_d_ild_db", "ResIld", "{:.2f}")):
                M.num(f"{tag}{key}", r["test"][metric][0], fmt)
            M.num(f"{tag}Heldout", r["heldout"]["si_sdr_i"][0])
            M.num(f"{tag}Params", r["params"] / 1e3, "{:.0f}")
        nc_lats = sorted({float(r["spec"]["latency_ms"]) for r in ev["runs"].values()
                          if not r["spec"].get("causal", True) and r["spec"]["family"] == "stft_asym"})
        gaps = [L for L in nc_lats if L < 32] or lats[:1]
        if orc:
            fig_gap(orc, ev, head, gaps, out, long_steps=(cfg.get("long_check") or {}).get("steps"),
                    short_steps=cfg["train"]["steps"])
            for L in gaps:
                t = gap_terms(orc, ev, head, L)
                for k, v in (t or {}).items():
                    M.num(f"Gap{k.capitalize()}{L:g}ms", v)
        lc = cfg.get("long_check") or {}
        if lc.get("steps"):
            st = lc["steps"]
            c32l, c4l = run_get(ev, "stft_asym", 32, head, steps=st), run_get(ev, "stft_asym", 4, head, steps=st)
