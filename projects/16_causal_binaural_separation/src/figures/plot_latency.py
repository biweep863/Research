def _fix(name: str) -> str:
    name = re.sub(r"(\d+)", lambda m: "".join(DIGIT_WORD[c] for c in m.group(1)), name)
    return re.sub(r"[^A-Za-z]", "", name)


class Macros:
    def __init__(self):
        self.lines = ["% Auto-generated by src/figures/plot_latency.py -- do not edit by hand."]

    def num(self, name: str, v, fmt: str = "{:.2f}"):
        s = "n/a" if v is None or (isinstance(v, float) and not np.isfinite(v)) else fmt.format(v)
        self.lines.append(f"\\newcommand{{\\{_fix(name)}}}{{{s}}}")

    def text(self, name: str, s: str):
        self.lines.append(f"\\newcommand{{\\{_fix(name)}}}{{{s}}}")

    def write(self, path: Path):
        path.write_text("\n".join(self.lines) + "\n")


def load(R: Path):
    def j(name):
        f = R / name
        return json.loads(f.read_text()) if f.exists() else None

    return j("oracle_sweep.json"), j("eval_summary.json"), j("bench_latency.json"), j("data_summary.json")


def oracle_curve(orc, kind, window, split="test", metric="si_sdr_i"):
    pts = sorted((e["latency_ms"], e["summary"][metric]) for e in orc["entries"]
                 if e["kind"] == kind and e["set"] == split and (e["window"] == window
                                                                 or (window == "sym" and e["latency_ms"] >= 32)))
    return pts


def run_get(ev, family, lat, head=None, causal=True, lookahead=0, split="test", metric="si_sdr_i", steps=None):
    for r in ev["runs"].values():
        s = r["spec"]
        if (s["family"] == family and float(s["latency_ms"]) == float(lat) and s.get("causal", True) == causal
                and s.get("lookahead", 0) == lookahead and (head is None or s.get("head") == head)
                and s.get("steps") == steps):
            return r[split][metric]
    return None


def family_curve(ev, fam, head, metric="si_sdr_i", split="test", causal=True):
    lats = sorted({float(r["spec"]["latency_ms"]) for r in ev["runs"].values()})
    out = []
    for L in lats:
        v = run_get(ev, fam, L, head, causal=causal, split=split, metric=metric)
        if v is None and fam == "stft_sym":  # sym == asym at the analysis-window length
            v = run_get(ev, "stft_asym", L, head, causal=causal, split=split, metric=metric) if L >= 32 else None
        if v is not None:
            out.append((L, v))
    return out


def _errplot(ax, pts, **kw):
    if not pts:
        return
    x = np.array([p[0] for p in pts])
    m = np.array([p[1][0] for p in pts])
    lo = np.array([p[1][1] for p in pts])
    hi = np.array([p[1][2] for p in pts])
    kw.setdefault("ms", 4)
    ax.errorbar(x, m, yerr=[m - lo, hi - m], capsize=2, **kw)


def fig_quality(orc, ev, head, out: Path):
    apply_style()
    fig, axes = plt.subplots(1, 2, figsize=(6.75, 2.9))
    for ax, metric, ylab in ((axes[0], "si_sdr_i", "SI-SDR improvement (dB)"), (axes[1], "estoi", "ESTOI")):
        if orc:
            _errplot(ax, oracle_curve(orc, "oracle_ear", "asym", metric=metric), color="k", ls="-", marker="",
                     label="Oracle IRM, asym.")
            _errplot(ax, oracle_curve(orc, "oracle_ear", "sym", metric=metric), color="k", ls="--", marker="",
                     label="Oracle IRM, sym.")
            _errplot(ax, oracle_curve(orc, "wiener", "asym", metric=metric), color="0.6", ls=":", marker="x",
                     label="Binaural Wiener")
            if metric == "estoi":
                un = [e for e in orc["entries"] if e["kind"] == "unprocessed" and e["set"] == "test"]
                if un:
                    ax.axhline(un[0]["summary"]["estoi"][0], color="0.4", lw=0.8, ls="-.", label="Unprocessed")
        if ev:
            for fam, st in FAM_STYLE.items():
                _errplot(ax, family_curve(ev, fam, head, metric), ls="-", **st)
                nc = family_curve(ev, fam, head, metric, causal=False)
                if nc:
                    _errplot(ax, nc, ls="none", mfc="white", color=st["color"], marker=st["marker"],
                             label=f"{st['label'].split(' (')[0]}, non-causal")
            for causal, mk in ((True, "*"), (False, "P")):
                long_pts = sorted((float(r["spec"]["latency_ms"]), r["test"][metric]) for r in ev["runs"].values()
                                  if r["spec"].get("steps") and r["spec"].get("causal", True) == causal)
                if long_pts:
                    steps_k = next(r["spec"]["steps"] for r in ev["runs"].values() if r["spec"].get("steps")) // 1000
                    _errplot(ax, long_pts, ls=":" if causal else "none", color="#0b2e6b", marker=mk, ms=6,
                             label=f"AsymDF {steps_k}k steps" + ("" if causal else ", non-causal"))
        ax.set_xscale("log", base=2)
        ax.set_xticks([1, 2, 4, 8, 16, 32])
        ax.set_xticklabels(["1", "2", "4", "8", "16", "32"])
        ax.set_xlabel("Algorithmic latency (ms)")
        ax.set_ylabel(ylab)
        ax.axvspan(0.8, 5, color="#f2c94c", alpha=0.12, lw=0)
    h, lab = axes[0].get_legend_handles_labels()
    fig.legend(h, lab, loc="lower center", ncol=4, fontsize=6, frameon=False, bbox_to_anchor=(0.5, -0.02))
    fig.tight_layout(rect=(0, 0.17, 1, 1))
